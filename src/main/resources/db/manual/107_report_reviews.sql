-- 신고 심사 권한, 상태 변경 및 열람 이력을 추가한다. 091_reports.sql 이후 적용한다.
BEGIN;

CREATE TABLE IF NOT EXISTS report_reviewers (
    user_id BIGINT PRIMARY KEY REFERENCES users(id),
    granted_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS report_reviewer_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES report_reviewers(user_id),
    enabled BOOLEAN NOT NULL,
    database_actor TEXT NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

ALTER TABLE reports
    ADD COLUMN IF NOT EXISTS version BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS review_started_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS review_started_by BIGINT REFERENCES users(id),
    ADD COLUMN IF NOT EXISTS closed_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS closed_by BIGINT REFERENCES users(id);

UPDATE reports SET updated_at = created_at WHERE updated_at IS NULL;

ALTER TABLE reports
    ALTER COLUMN updated_at SET DEFAULT clock_timestamp(),
    ALTER COLUMN updated_at SET NOT NULL,
    DROP CONSTRAINT IF EXISTS reports_status_check;

ALTER TABLE reports
    ADD CONSTRAINT reports_status_check CHECK (status IN ('RECEIVED','IN_REVIEW','RESOLVED','DISMISSED'));

CREATE TABLE IF NOT EXISTS report_review_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    from_status VARCHAR(20) NOT NULL,
    to_status VARCHAR(20) NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES users(id),
    reason VARCHAR(1000),
    created_at TIMESTAMPTZ NOT NULL,
    version BIGINT NOT NULL CHECK (version > 0),
    request_id UUID NOT NULL,
    CONSTRAINT uk_report_review_version UNIQUE (report_id, version),
    CONSTRAINT uk_report_review_request UNIQUE (actor_id, request_id),
    CONSTRAINT ck_report_review_transition CHECK (
        (from_status = 'RECEIVED' AND to_status = 'IN_REVIEW')
        OR (from_status = 'IN_REVIEW' AND to_status IN ('RESOLVED','DISMISSED')
            AND reason IS NOT NULL AND reason ~ '[^[:space:]]')
    )
);

CREATE TABLE IF NOT EXISTS report_review_access_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    actor_id BIGINT NOT NULL REFERENCES users(id),
    access_type VARCHAR(20) NOT NULL CHECK (access_type IN ('DETAIL','MESSAGES','IMAGE')),
    message_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS ix_reports_review_status_created ON reports(status, created_at, id);
CREATE INDEX IF NOT EXISTS ix_reports_review_created ON reports(created_at, id);
CREATE INDEX IF NOT EXISTS ix_report_review_access_report ON report_review_access_log(report_id);

COMMIT;
