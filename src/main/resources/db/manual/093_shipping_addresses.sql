BEGIN;
CREATE TABLE IF NOT EXISTS user_shipping_addresses (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 label VARCHAR(30), recipient_name VARCHAR(50) NOT NULL,
 recipient_phone VARCHAR(12) NOT NULL, postal_code VARCHAR(5) NOT NULL,
 address_line1 VARCHAR(255) NOT NULL, address_line2 VARCHAR(255), delivery_memo VARCHAR(200),
 is_default BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMP NOT NULL, updated_at TIMESTAMP NOT NULL,
 CONSTRAINT ck_shipping_address_values CHECK (length(trim(recipient_name))>0 AND recipient_phone ~ '^[0-9]{9,12}$' AND postal_code ~ '^[0-9]{5}$' AND length(trim(address_line1))>0)
);
CREATE INDEX IF NOT EXISTS ix_shipping_addresses_user ON user_shipping_addresses(user_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_shipping_address_default ON user_shipping_addresses(user_id) WHERE is_default;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_recipient_name VARCHAR(50);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_recipient_phone VARCHAR(12);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_postal_code VARCHAR(5);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_address_line1 VARCHAR(255);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_address_line2 VARCHAR(255);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS shipping_delivery_memo VARCHAR(200);
COMMIT;
