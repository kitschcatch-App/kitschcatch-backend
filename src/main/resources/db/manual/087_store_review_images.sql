-- 리뷰 사진 업로드 상태와 소유권 및 리뷰 내 정렬 제약을 구성한다.
BEGIN;
CREATE UNIQUE INDEX IF NOT EXISTS uk_store_reviews_image_owner ON store_reviews(id,store_id,author_id);
CREATE TABLE IF NOT EXISTS store_review_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES users(id),
    store_id BIGINT NOT NULL REFERENCES stores(id),
    review_id BIGINT,
    sort_order INTEGER,
    temporary_key VARCHAR(200) NOT NULL UNIQUE,
    object_key VARCHAR(200) NOT NULL UNIQUE,
    content_type VARCHAR(30) NOT NULL,
    expected_size BIGINT NOT NULL,
    state VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    cleanup_at TIMESTAMPTZ NOT NULL,
    temporary_cleaned BOOLEAN NOT NULL DEFAULT FALSE,
    cleanup_attempts INTEGER NOT NULL DEFAULT 0,
    width INTEGER,
    height INTEGER,
    CONSTRAINT fk_review_images_owner FOREIGN KEY(review_id,store_id,owner_id)
        REFERENCES store_reviews(id,store_id,author_id),
    CONSTRAINT uk_review_images_order UNIQUE(review_id,sort_order),
    CONSTRAINT ck_review_images_type CHECK(content_type IN ('image/jpeg','image/png','image/webp')),
    CONSTRAINT ck_review_images_size CHECK(expected_size BETWEEN 1 AND 5242880),
    CONSTRAINT ck_review_images_state CHECK(state IN ('PENDING','READY','ATTACHED','DELETE_PENDING','DELETED')),
    CONSTRAINT ck_review_images_attachment CHECK(
        (state = 'ATTACHED' AND review_id IS NOT NULL AND sort_order IS NOT NULL AND sort_order BETWEEN 0 AND 9)
        OR (state <> 'ATTACHED' AND review_id IS NULL AND sort_order IS NULL)),
    CONSTRAINT ck_review_images_dimensions CHECK(
        state NOT IN ('READY','ATTACHED') OR (width IS NOT NULL AND height IS NOT NULL AND width BETWEEN 1 AND 1600 AND height BETWEEN 1 AND 1600)),
    CONSTRAINT ck_review_images_temporary_key CHECK(
        temporary_key ~ ('^store-review-uploads/' || owner_id || '/[0-9a-f-]{36}$')),
    CONSTRAINT ck_review_images_object_key CHECK(
        object_key ~ ('^store-review-images/' || store_id || '/' || owner_id || '/[0-9a-f-]{36}[.]png$'))
);
CREATE INDEX IF NOT EXISTS ix_review_images_owner_created ON store_review_images(owner_id,created_at);
CREATE INDEX IF NOT EXISTS ix_review_images_store ON store_review_images(store_id,review_id);
CREATE INDEX IF NOT EXISTS ix_review_images_cleanup ON store_review_images(cleanup_at,id) WHERE state <> 'DELETED';
COMMIT;
