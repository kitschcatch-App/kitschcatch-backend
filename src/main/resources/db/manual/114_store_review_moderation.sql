-- 리뷰 조치 권한과 신고 만료 이후에도 남는 조치 이력을 추가한다.
BEGIN;
ALTER TABLE store_reviews ADD COLUMN IF NOT EXISTS evidence_until timestamptz;
CREATE TABLE IF NOT EXISTS store_review_moderators (
    user_id bigint PRIMARY KEY REFERENCES users(id),
    granted_at timestamptz NOT NULL DEFAULT now(),
    revoked_at timestamptz
);
CREATE TABLE IF NOT EXISTS store_review_moderator_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES store_review_moderators(user_id),
    enabled boolean NOT NULL,
    database_actor text NOT NULL,
    reason varchar(1000) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS store_review_moderation_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id bigint NOT NULL REFERENCES store_reviews(id),
    actor_id bigint NOT NULL REFERENCES users(id),
    report_id bigint NOT NULL,
    reporter_id bigint NOT NULL,
    action varchar(10) NOT NULL CHECK (action IN ('HIDE','RESTORE')),
    reason varchar(1000) NOT NULL CHECK (length(trim(reason)) > 0),
    request_id uuid NOT NULL,
    version bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(actor_id, request_id),
    UNIQUE(review_id, version)
);
COMMIT;
