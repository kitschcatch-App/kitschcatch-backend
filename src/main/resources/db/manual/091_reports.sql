-- 대상별 신고 내용과 접수 당시 기록 및 만료 정리 인덱스를 생성한다.
BEGIN;
CREATE TABLE IF NOT EXISTS reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users(id),
    target_type VARCHAR(30) NOT NULL CHECK (target_type IN ('USER','POST','CHAT_ROOM','STORE_REVIEW')),
    target_id BIGINT NOT NULL CHECK (target_id > 0),
    target_user_id BIGINT NOT NULL REFERENCES users(id),
    reason_code VARCHAR(40) NOT NULL CHECK (reason_code IN ('SPAM','HARASSMENT','FRAUD_SUSPECTED','IMPERSONATION','PROHIBITED_ITEM','COUNTERFEIT_SUSPECTED','INAPPROPRIATE_CONTENT','PERSONAL_INFORMATION','OFF_TOPIC','OTHER')),
    description VARCHAR(1000) NOT NULL,
    request_fingerprint VARCHAR(64) NOT NULL,
    message_ids JSONB NOT NULL CHECK (jsonb_typeof(message_ids)='array' AND jsonb_array_length(message_ids)<=10),
    target_snapshot JSONB NOT NULL CHECK (jsonb_typeof(target_snapshot)='object'),
    snapshot_version INTEGER NOT NULL DEFAULT 1 CHECK (snapshot_version = 1),
    status VARCHAR(20) NOT NULL DEFAULT 'RECEIVED' CHECK (status = 'RECEIVED'),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL CHECK (expires_at > created_at),
    CONSTRAINT uk_reports_reporter_target UNIQUE (reporter_id, target_type, target_id),
    CONSTRAINT ck_reports_other_description CHECK (reason_code <> 'OTHER' OR description ~ '[^[:space:]]'),
    CONSTRAINT ck_reports_not_self CHECK (reporter_id <> target_user_id)
);
CREATE INDEX IF NOT EXISTS ix_reports_reporter_created ON reports(reporter_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS ix_reports_target ON reports(target_type, target_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_reports_expiry ON reports(expires_at, id);
COMMIT;
