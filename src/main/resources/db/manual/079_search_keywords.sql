-- 검색어 기록·일일 집계·방향성 연관어의 제약과 조회 인덱스를 생성한다.
BEGIN;
CREATE TABLE IF NOT EXISTS recent_searches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 keyword_key VARCHAR(64) NOT NULL, display_keyword VARCHAR(1000) NOT NULL,
 normalized_keyword VARCHAR(1000) NOT NULL, last_searched_at TIMESTAMPTZ NOT NULL,
 UNIQUE(user_id,keyword_key), CHECK(length(display_keyword)>0), CHECK(length(normalized_keyword)>0)
);
CREATE INDEX IF NOT EXISTS ix_recent_user_time ON recent_searches(user_id,last_searched_at DESC,id DESC);
CREATE TABLE IF NOT EXISTS search_daily_users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 search_date DATE NOT NULL, keyword_key VARCHAR(64) NOT NULL, normalized_keyword VARCHAR(1000) NOT NULL,
 UNIQUE(search_date,user_id,keyword_key), CHECK(length(normalized_keyword)>0)
);
CREATE INDEX IF NOT EXISTS ix_search_day_keyword ON search_daily_users(search_date,keyword_key);
CREATE TABLE IF NOT EXISTS related_search_keywords (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_key VARCHAR(64) NOT NULL, source_keyword VARCHAR(1000) NOT NULL,
 target_key VARCHAR(64) NOT NULL, target_keyword VARCHAR(1000) NOT NULL,
 priority INTEGER NOT NULL, active BOOLEAN NOT NULL,
 UNIQUE(source_key,target_key), CHECK(source_key<>target_key), CHECK(priority>=0),
 CHECK(length(source_keyword)>0), CHECK(length(target_keyword)>0)
);
CREATE INDEX IF NOT EXISTS ix_related_source ON related_search_keywords(source_key,active,priority,id);
COMMIT;
