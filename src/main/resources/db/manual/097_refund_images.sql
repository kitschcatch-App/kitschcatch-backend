-- 주문에 귀속된 비공개 반품 사진과 첨부 무결성 제약을 생성한다.
BEGIN;
CREATE UNIQUE INDEX IF NOT EXISTS uk_orders_refund_image_buyer ON orders(id, user_id);
CREATE UNIQUE INDEX IF NOT EXISTS uk_orders_refund_image_refund ON orders(id, refund_id);
CREATE TABLE IF NOT EXISTS refund_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    uploader_id BIGINT NOT NULL,
    temporary_key VARCHAR(200) NOT NULL UNIQUE,
    object_key VARCHAR(200) NOT NULL UNIQUE,
    content_type VARCHAR(30) NOT NULL,
    expected_size BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    cleanup_at TIMESTAMPTZ NOT NULL,
    temporary_cleaned BOOLEAN NOT NULL DEFAULT FALSE,
    cleanup_attempts INTEGER NOT NULL DEFAULT 0,
    state VARCHAR(20) NOT NULL,
    refund_id VARCHAR(50),
    sort_order INTEGER,
    width INTEGER,
    height INTEGER,
    sha256 VARCHAR(64),
    CONSTRAINT fk_refund_images_buyer FOREIGN KEY (order_id, uploader_id) REFERENCES orders(id, user_id),
    CONSTRAINT fk_refund_images_refund FOREIGN KEY (order_id, refund_id) REFERENCES orders(id, refund_id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT uk_refund_images_sort_order UNIQUE (refund_id, sort_order),
    CONSTRAINT ck_refund_images_type CHECK (content_type IN ('image/jpeg', 'image/png', 'image/webp')),
    CONSTRAINT ck_refund_images_size CHECK (expected_size BETWEEN 1 AND 5242880),
    CONSTRAINT ck_refund_images_state CHECK (state IN ('PENDING', 'READY', 'ATTACHED')),
    CONSTRAINT ck_refund_images_dates CHECK (expires_at > created_at AND cleanup_at >= expires_at AND cleanup_attempts >= 0),
    CONSTRAINT ck_refund_images_attachment CHECK (
        (state = 'ATTACHED' AND refund_id IS NOT NULL AND sort_order IS NOT NULL AND sort_order BETWEEN 0 AND 4)
        OR (state <> 'ATTACHED' AND refund_id IS NULL AND sort_order IS NULL)),
    CONSTRAINT ck_refund_images_verification CHECK (
        (state = 'PENDING' AND width IS NULL AND height IS NULL AND sha256 IS NULL)
        OR (state <> 'PENDING' AND width IS NOT NULL AND height IS NOT NULL AND sha256 IS NOT NULL
            AND width BETWEEN 1 AND 1600 AND height BETWEEN 1 AND 1600 AND sha256 ~ '^[0-9a-f]{64}$')),
    CONSTRAINT ck_refund_images_temporary_key CHECK (
        temporary_key ~ ('^refund-uploads/' || order_id || '/[0-9a-f-]{36}$')),
    CONSTRAINT ck_refund_images_object_key CHECK (
        object_key ~ ('^refund-images/' || order_id || '/[0-9a-f-]{36}[.]png$'))
);
CREATE INDEX IF NOT EXISTS ix_refund_images_order ON refund_images(order_id, refund_id);
CREATE INDEX IF NOT EXISTS ix_refund_images_uploader ON refund_images(uploader_id, created_at);
CREATE INDEX IF NOT EXISTS ix_refund_images_cleanup ON refund_images(cleanup_at, id)
    WHERE state <> 'ATTACHED' OR NOT temporary_cleaned;
COMMIT;
