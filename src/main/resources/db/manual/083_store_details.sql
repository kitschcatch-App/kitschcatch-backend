-- 기존 매장에 소개와 운영자가 검수한 사진·편의시설을 연결한다.
BEGIN;

ALTER TABLE stores ADD COLUMN IF NOT EXISTS description VARCHAR(1000);

CREATE TABLE IF NOT EXISTS store_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
    object_key VARCHAR(180) NOT NULL,
    sort_order INTEGER NOT NULL,
    caption VARCHAR(200),
    credit VARCHAR(200),
    source_url VARCHAR(1000),
    CONSTRAINT uk_store_images_key UNIQUE (object_key),
    CONSTRAINT uk_store_images_sort UNIQUE (store_id, sort_order) DEFERRABLE INITIALLY IMMEDIATE,
    CONSTRAINT ck_store_images_sort CHECK (sort_order BETWEEN 0 AND 9),
    CONSTRAINT ck_store_images_key CHECK (object_key ~ (
        '^stores/' || store_id || '/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}[.](jpg|png|webp)$'
    ))
);

CREATE TABLE IF NOT EXISTS store_amenities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES stores(id) ON DELETE CASCADE,
    code VARCHAR(24) NOT NULL,
    status VARCHAR(16) NOT NULL,
    note VARCHAR(300),
    CONSTRAINT uk_store_amenities_code UNIQUE (store_id, code),
    CONSTRAINT ck_store_amenities_code CHECK (code IN (
        'PARKING', 'RESTROOM', 'WIFI', 'ELEVATOR', 'WHEELCHAIR_ACCESS', 'PET_FRIENDLY'
    )),
    CONSTRAINT ck_store_amenities_status CHECK (status IN ('AVAILABLE', 'UNAVAILABLE'))
);

CREATE TABLE IF NOT EXISTS store_content_imports (
    id UUID PRIMARY KEY,
    input_sha256 CHAR(64) NOT NULL CHECK (input_sha256 ~ '^[0-9a-f]{64}$'),
    store_ids BIGINT[] NOT NULL,
    reviewer VARCHAR(120) NOT NULL,
    reviewed_at TIMESTAMPTZ NOT NULL,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
